export function textWidth(str, scale) { return String(str).length * 6 * scale - scale; }
export function drawText(gfx, str, x, y, scale, color) {
  const s = String(str).toUpperCase();
  let cx = x;
  for (const ch of s) {
    const glyph = G[ch] || G['?'];
    for (let r = 0; r < 7; r++) {
      const bits = glyph[r];
      for (let c = 0; c < 5; c++) {
        if (bits & (16 >> c)) gfx.rect(cx + c * scale, y + r * scale, scale, scale, color);
      }
    }
    cx += 6 * scale;
  }
}
export function drawTextCentered(gfx, str, cx, y, scale, color) {
  drawText(gfx, str, Math.round(cx - textWidth(str, scale) / 2), y, scale, color);
}
